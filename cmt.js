  function collectTextNodes(phrase, targetSelector, excludeSelector) {
    var found = [];
    var root = document.querySelector('.container') || document.body;
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    var n;
    while ((n = walker.nextNode())) {
      var p = n.parentElement;
      if (!p) continue;
      if (p.closest('.dist-note') || p.closest('.res-note')) continue;
      if (targetSelector && !p.closest(targetSelector)) continue;
      if (excludeSelector && p.closest(excludeSelector)) continue;
      if (n.nodeValue.indexOf(phrase) !== -1) found.push(n);
    }
    return found;
  }

  function insertNotes(notesList, className, targetSelector, excludeSelector) {
    notesList.forEach(function (pair) {
      var phrase = pair[0], note = pair[1];
      collectTextNodes(phrase, targetSelector, excludeSelector).forEach(function (node) {
        var text = node.nodeValue;
        var cut = text.indexOf(phrase) + phrase.length;
        var before = document.createTextNode(text.slice(0, cut));
        var span = document.createElement('span');
        span.className = className;
        span.textContent = ' (' + note + ') ';
        var after = document.createTextNode(text.slice(cut));
        var parent = node.parentNode;
        parent.insertBefore(before, node);
        parent.insertBefore(span, node);
        parent.insertBefore(after, node);
        parent.removeChild(node);
      });
    });
  }

